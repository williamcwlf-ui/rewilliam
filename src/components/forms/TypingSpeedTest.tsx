export function TypingSpeedTest({
  label,
  id = 'TypingSpeedTest',
}: {
  label?: string;
  id?: string;
}) {
  const [currentWords, setCurrentWords] = useState(getRandomWords(500));
  const [value, setValue] = useState('');
  const [timeLeft, setTimeLeft] = useState<number | null>(null);
  const [totalWords, setTotalWords] = useState(0);
  const [result, setResult] = useState<string | null>(null);
  const inputRef = useRef(null);
  const [started, setStarted] = useState(false);

  function getRandomWord(): string {
    return words[Math.floor(Math.random() * words.length)] as string;
  }

  function getRandomWords(num: number): string[] {
    const randomWords: string[] = [];
    for (let i = 0; i < num; i++) {
      randomWords.push(getRandomWord());
    }
    return randomWords;
  }

  useEffect(() => {
    if (timeLeft == null) return;
    if (timeLeft > 0 && typeof timeLeft == 'number') {
      const timerId = setTimeout(() => {
        setTimeLeft(timeLeft - 1);
      }, 1000);
      return () => clearTimeout(timerId);
    } else if (timeLeft === 0) {
      setResult(`Your typing speed is ${totalWords} WPM.`);
    }
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [timeLeft]);

  function handleChange(event: any) {
    if (!started) {
      setTimeLeft(60);
      setStarted(true);
    }

    setValue(event.target.value);

    if (event.target.value.trim() === currentWords[0]) {
      setTotalWords(totalWords + 1);
      setCurrentWords(currentWords.slice(1));
      setValue('');
    }
  }

  return (
    <div className="flex flex-col py-2">
      <p className="mb-6">{label || 'Typing Speed Test'}</p>
      {!result && (
        <div className="text-2xl mb-4 text-center flex justify-center flex-row gap-2">
          {currentWords.slice(0, 5).map((word, index) => (
            <span key={index} className={index === 0 ? 'typed-word' : 'word'}>
              {word}
            </span>
          ))}
        </div>
      )}
      <div className="mb-4 text-center">
        {result
          ? result
          : timeLeft
            ? `${timeLeft} seconds left`
            : 'Start typing to begin the test'}
      </div>
      {!result && (
        <input
          type="text"
          className="border border-gray-300 dark:border-gray-700 bg-white dark:bg-gray-800 text-gray-900 dark:text-gray-100 placeholder-gray-400 dark:placeholder-gray-500 p-2 rounded mb-4 focus:outline-none focus:ring-2 focus:ring-blue-500/50"
          ref={inputRef}
          value={value}
          required={true}
          onChange={handleChange}
        />
      )}
      <input
        id={id}
        name={id}
        type="number"
        value={totalWords}
        className="hidden"
      />
    </div>
  );
}
